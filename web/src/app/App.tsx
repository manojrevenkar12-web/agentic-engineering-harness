import { MotionConfig } from "motion/react";
import { Budget } from "../features/budget/Budget";
import { Certainty } from "../features/certainty/Certainty";
import { Graders } from "../features/graders/Graders";
import { Heldout } from "../features/heldout/Heldout";
import { TaskMatrix } from "../features/tasks/TaskMatrix";
import { Verdict } from "../features/verdict/Verdict";
import { useResults } from "../shared/lib/useResults";
import { Section, slice } from "../shared/ui/Section";
import s from "./app.module.css";

const runIt = (
  <p>
    Run <code>aeh bench</code>, then <code>aeh report</code> and <code>npm run sync</code>.
  </p>
);

export function App({ url }: { url?: string }) {
  const { state, retry } = useResults(url);
  const withDev = slice(state, (r) => (r.dev ? r : null));
  return (
    <MotionConfig reducedMotion="user">
      <a className={s.skip} href="#verdict">
        Skip to the results
      </a>
      <div className={s.page}>
        <header className={s.masthead}>
          <h1 className={s.h1}>Which way of working with coding agents should the team adopt?</h1>
          <p className={s.lede}>
            Real Claude Code agents worked a backlog of tickets on an AI-infrastructure codebase, each in its own sandbox. Every change was graded the way a
            maintainer would grade it, not only by its tests.
          </p>
          <nav aria-label="Sections" className={s.nav}>
            <a href="#verdict">Decision</a>
            <a href="#certainty">How sure</a>
            <a href="#tasks">By task</a>
            <a href="#graders">Graders</a>
            <a href="#heldout">Held-out</a>
            <a href="#budget">Cost</a>
          </nav>
        </header>
        <main>
          <Section
            id="verdict"
            title="Passing the tests is not the same as mergeable"
            intro="The gap between the two marks is work a person would have sent back."
            load={withDev}
            onRetry={retry}
            skeletonRows={6}
            empty={{ title: "No benchmark has run yet", body: runIt }}
          >
            {(r) => <Verdict r={r} />}
          </Section>
          <Section
            id="certainty"
            title="Which differences are real?"
            intro="A dozen tasks cannot separate small differences, so every comparison is paired by task and shown with its interval."
            load={withDev}
            onRetry={retry}
            empty={{ title: "No benchmark has run yet", body: runIt }}
          >
            {(r) => <Certainty r={r} />}
          </Section>
          <Section
            id="tasks"
            title="Task by task"
            intro="Merged changes out of attempts, for every task and setup."
            load={withDev}
            onRetry={retry}
            empty={{ title: "No benchmark has run yet", body: runIt }}
          >
            {(r) => <TaskMatrix r={r} />}
          </Section>
          <Section
            id="graders"
            title="Graders proven before they grade"
            intro="Each task ships with a reference change, plausible wrong changes and changes that pass the tests but should not be merged. A grader is used only once it sorts all of them correctly."
            load={slice(state, (r) => r.proofs.dev)}
            onRetry={retry}
            empty={{
              title: "No grader has been proven yet",
              body: (
                <p>
                  Run <code>aeh prove --set dev</code>.
                </p>
              ),
            }}
          >
            {(p) => <Graders p={p} />}
          </Section>
          <Section
            id="heldout"
            title="Tasks nobody tuned on"
            intro="Written from a short guide by someone who never read the harness, and run once."
            load={slice(state, (r) => (r.heldout ? r : null))}
            onRetry={retry}
            empty={{
              title: "The held-out tasks have not run",
              body: (
                <p>
                  Run <code>aeh heldout</code> once; the first run is recorded and never rewritten.
                </p>
              ),
            }}
          >
            {(r) => <Heldout h={r.heldout!} setups={r.setups} />}
          </Section>
          <Section id="budget" title="What it cost" load={withDev} onRetry={retry} empty={{ title: "No benchmark has run yet", body: runIt }}>
            {(r) => <Budget r={r} />}
          </Section>
        </main>
        {state.status === "ready" ? (
          <footer className={s.footer}>
            <p>
              Generated by <code>aeh report</code> on{" "}
              {new Date(state.data.generated_at).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" })}. Every number comes from
              reports/results.json.
            </p>
            <p>Costs are Claude Code's own reports at list prices. The tasks are on a portfolio codebase, not a customer's.</p>
          </footer>
        ) : null}
      </div>
    </MotionConfig>
  );
}
